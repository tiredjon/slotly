'''Напиши код. Брони: booked = {540, 600, 660}.
Услуга длится 60 минут, то есть занимает два слота подряд: t и t + 30.
Найди с помощью for ... else первое время из range(540, 1080, 30), на которое её можно поставить. 
Если такого нет, напечатай «Нет места». Перед запуском предскажи, какое время найдётся.'''

booked = {540,600,660}
for i in range(540, 1050, 30):
    if i not in booked and (i + 30) not in booked:
        print(i)
        break
else:
    print("Slot not found")